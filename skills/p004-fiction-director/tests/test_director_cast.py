"""Free, no-API casting planner tests for the isolated new fictional story."""
import copy
import importlib.util
import json
import pathlib
import unittest

ROOT=pathlib.Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location("p004_director_cast",ROOT/"scripts"/"director_cast.py")
mod=importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
ROSTER=json.loads((ROOT/"characters"/"drafts"/"roster-v2.json").read_text(encoding="utf-8"))


def req(**overrides):
    s={"simulation_only":True,"source_status":"HYPOTHETICAL",
       "story_date":"2026-10-14","daypart":"afternoon",
       "topic_keywords":["能源","交通"],"max_members":8}
    s.update(overrides)
    return s


class CastingTests(unittest.TestCase):
    def test_cast_contains_only_unapproved_65_character_ids(self):
        out=mod.plan(ROSTER,req())
        actual={p["id"] for p in ROSTER["people"]}
        self.assertGreater(out["cast_count"],0)
        self.assertTrue(set(m["speaker_id"] for m in out["cast"])<=actual)
        self.assertTrue(all(m["silence_allowed"] for m in out["cast"]))
        self.assertFalse(out["publishable"])
        self.assertTrue(out["draft_only"])
        self.assertTrue(out["no_autogenerated_dialogue"])
        self.assertTrue(out["no_trading_or_publication_side_effects"])

    def test_cast_has_reasons_and_interest_not_random(self):
        out=mod.plan(ROSTER,req(topic_keywords=["能源"]))
        self.assertGreater(out["cast_count"],0)
        self.assertTrue(all(c["matched_reasons"] and c["score"]>=2 for c in out["cast"]))
        self.assertGreaterEqual(len({x["main_behavior"] for x in out["cast"]}),2)

    def test_reproducible_plan(self):
        self.assertEqual(mod.plan(ROSTER,req()),mod.plan(ROSTER,req()))

    def test_simulated_professor_only_in_evening_on_weekday(self):
        self.assertFalse(mod.plan(ROSTER,req(daypart="morning"))["professor_allowed"])
        self.assertTrue(mod.plan(ROSTER,req(daypart="evening"))["professor_allowed"])
        self.assertFalse(mod.plan(ROSTER,req(daypart="evening",story_date="2026-10-11"))["professor_allowed"])

    def test_recent_speaker_penalized(self):
        base=mod.plan(ROSTER,req(topic_keywords=["能源"],max_members=15))
        first=base["cast"][0]["speaker_id"]
        changed=mod.plan(ROSTER,req(topic_keywords=["能源"],max_members=15,recent_member_ids=[first]))
        old={x["speaker_id"]:x["score"] for x in base["cast"]}
        new={x["speaker_id"]:x["score"] for x in changed["cast"]}
        self.assertTrue(first not in new or new[first] == old[first]-4)

    def test_member_limit_and_empty_topic_relevance(self):
        self.assertLessEqual(mod.plan(ROSTER,req(max_members=2))["cast_count"],2)
        self.assertEqual([],mod.plan(ROSTER,req(topic_keywords=["无匹配的测试词XYZ"]))["cast"])

    def test_do_not_implicitly_use_old_personas_or_approved_people(self):
        bad=copy.deepcopy(ROSTER)
        bad["story_id"]="romania-market-director"
        with self.assertRaisesRegex(ValueError,"legacy"):
            mod.plan(bad,req())
        bad=copy.deepcopy(ROSTER)
        bad["people"][0]["approved_by_user"]=True
        with self.assertRaisesRegex(ValueError,"altered"):
            mod.plan(bad,req())

    def test_no_unverified_news_published_as_fact(self):
        with self.assertRaisesRegex(ValueError,"hypothetical"):
            mod.plan(ROSTER,req(source_status="VERIFIED"))
        with self.assertRaisesRegex(ValueError,"hypothetical"):
            mod.plan(ROSTER,req(source_status="UNVERIFIED"))
        with self.assertRaisesRegex(ValueError,"rehearsal"):
            mod.plan(ROSTER,req(simulation_only=False))

    def test_reject_bad_session_specs(self):
        with self.assertRaisesRegex(ValueError,"daypart"):
            mod.plan(ROSTER,req(daypart="noon"))
        with self.assertRaisesRegex(ValueError,"max_members"):
            mod.plan(ROSTER,req(max_members=99))
        with self.assertRaisesRegex(ValueError,"invalid story_date"):
            mod.plan(ROSTER,req(story_date="2026-15-22"))
        with self.assertRaisesRegex(ValueError,"topic_keywords"):
            mod.plan(ROSTER,req(topic_keywords=[]))


if __name__=="__main__":
    unittest.main()
